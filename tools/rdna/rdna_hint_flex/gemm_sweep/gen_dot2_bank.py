"""Generate dot2_bank.hip: v_dot2c_f32_f16 throughput as a function of the VGPR
bank (register number mod 4) of its three operands.

The 8x8 micro-tile of the GEMM kernels issues 256 ``v_dot2c_f32_f16 acc, a, b``
per k-step. The compiler puts every ``a`` and ``b`` fragment in a 4-aligned
VGPR tuple (the destination of a ds_read_b128), so for each k-pair ``t`` the two
sources sit in the same bank. Whether that costs issue slots is a question about
the hardware, so each kernel here runs the 256-dot body from fixed physical
registers (inline asm, no compiler allocation) with the three register groups
offset by (dB, dC) banks relative to the A group and reports, per kernel, the
dot2 rate and the shader clock the kernel ran at.

  python3 gen_dot2_bank.py > dot2_bank.hip
  hipcc -O3 --offload-arch=gfx1030 dot2_bank.hip -o dot2_bank
  HIP_VISIBLE_DEVICES=<gpu> ./dot2_bank
"""

import itertools

TM = TN = 8
KT = 4  # k-pairs (dwords) per 16-byte fragment
A_BASE, B_BASE, C_BASE = 32, 72, 112  # all multiples of 4


def body(da: int, db: int, dc: int, order: str) -> list[str]:
    a = lambda i, t: f"v{A_BASE + da + KT * i + t}"  # noqa: E731
    b = lambda j, t: f"v{B_BASE + db + KT * j + t}"  # noqa: E731
    c = lambda i, j: f"v{C_BASE + dc + TN * i + j}"  # noqa: E731
    if (
        order == "tmajor"
    ):  # k-pair outermost: 64 independent accumulators between repeats
        idx = itertools.product(range(KT), range(TM), range(TN))
        return [f"v_dot2c_f32_f16 {c(i, j)}, {a(i, t)}, {b(j, t)}" for t, i, j in idx]
    idx = itertools.product(
        range(TM), range(TN), range(KT)
    )  # tinner: 4 dependent dots in a row
    return [f"v_dot2c_f32_f16 {c(i, j)}, {a(i, t)}, {b(j, t)}" for i, j, t in idx]


def clobbers() -> str:
    regs = list(range(A_BASE, A_BASE + 4 + KT * TM)) + list(
        range(B_BASE, B_BASE + 4 + KT * TN)
    )
    regs += list(range(C_BASE, C_BASE + 4 + TM * TN))
    return ", ".join(f'"v{r}"' for r in regs) + ', "memory"'


def kernel(da: int, db: int, dc: int, order: str) -> str:
    name = f"dot2_a{da}b{db}c{dc}_{order}"
    init = []
    for r in range(A_BASE + da, A_BASE + da + KT * TM):
        init.append(f"v_mov_b32 v{r}, 0x3c003c00")
    for r in range(B_BASE + db, B_BASE + db + KT * TN):
        init.append(f"v_mov_b32 v{r}, 0x3c003c00")
    for r in range(C_BASE + dc, C_BASE + dc + TM * TN):
        init.append(f"v_mov_b32 v{r}, 0")
    lines = init + ["1:"] + body(da, db, dc, order)
    lines += ["s_sub_u32 %0, %0, 1", "s_cmp_lg_u32 %0, 0", "s_cbranch_scc1 1b"]
    text = '\\n"\n      "'.join(lines)
    return f"""
__global__ __launch_bounds__(128) void {name}(unsigned long long* tm, unsigned iters) {{
  unsigned long long c0 = __builtin_amdgcn_s_memtime();
  unsigned long long r0 = __builtin_amdgcn_s_memrealtime();
  asm volatile("{text}"
               : "+s"(iters) : : {clobbers()});
  unsigned long long c1 = __builtin_amdgcn_s_memtime();
  unsigned long long r1 = __builtin_amdgcn_s_memrealtime();
  if ((threadIdx.x & 31) == 0) {{
    unsigned long long* o = tm + 4ull * ((blockIdx.x * blockDim.x + threadIdx.x) >> 5);
    o[0] = c1 - c0;
    o[1] = r1 - r0;
  }}
}}
"""


def main() -> None:
    combos = [(0, db, dc, "tmajor") for db in range(4) for dc in range(4)] + [
        (0, 0, 0, "tinner"),
        (0, 1, 0, "tinner"),
    ]
    print("// generated by gen_dot2_bank.py: do not edit")
    print(
        "#include <hip/hip_runtime.h>\n#include <algorithm>\n#include <cstdio>\n#include <vector>\n"
    )
    for da, db, dc, order in combos:
        print(kernel(da, db, dc, order))
    print(
        "struct K { const char* name; void (*fn)(unsigned long long*, unsigned); int da, db, dc; };"
    )
    print("static const K kernels[] = {")
    for da, db, dc, order in combos:
        n = f"dot2_a{da}b{db}c{dc}_{order}"
        print(f'  {{"{n}", {n}, {da}, {db}, {dc}}},')
    print("};")
    print(r"""
int main(int argc, char** argv) {
  const int blocks = argc > 1 ? atoi(argv[1]) : 144;   // 4 per WGP on the 36-WGP V620: 4 waves per SIMD
  const unsigned iters = argc > 2 ? (unsigned)atoi(argv[2]) : 100000;
  const int reps = argc > 3 ? atoi(argv[3]) : 3;
  const int nk = sizeof(kernels) / sizeof(kernels[0]);
  const int waves = blocks * 4;
  unsigned long long* tm;
  hipMalloc(&tm, waves * 4 * sizeof(unsigned long long));
  hipEvent_t e0, e1;
  hipEventCreate(&e0);
  hipEventCreate(&e1);
  std::vector<float> best(nk, 1e30f);
  std::vector<double> cyc(nk, 0), mhz(nk, 0);
  for (int k = 0; k < nk; ++k) kernels[k].fn<<<blocks, 128>>>(tm, 2000);  // warm up each kernel
  hipDeviceSynchronize();
  for (int r = 0; r < reps; ++r) {
    for (int ki = 0; ki < nk; ++ki) {
      int k = (r & 1) ? nk - 1 - ki : ki;
      hipEventRecord(e0);
      kernels[k].fn<<<blocks, 128>>>(tm, iters);
      hipEventRecord(e1);
      hipEventSynchronize(e1);
      float ms;
      hipEventElapsedTime(&ms, e0, e1);
      if (ms < best[k]) {
        best[k] = ms;
        std::vector<unsigned long long> h(waves * 4);
        hipMemcpy(h.data(), tm, h.size() * 8, hipMemcpyDeviceToHost);
        std::vector<double> c, t;
        for (int w = 0; w < waves; ++w) { c.push_back((double)h[4 * w]); t.push_back((double)h[4 * w + 1]); }
        std::sort(c.begin(), c.end());
        std::sort(t.begin(), t.end());
        cyc[k] = c[c.size() / 2];
        mhz[k] = c[c.size() / 2] / (t[t.size() / 2] / 100.0);  // s_memtime ticks per 100 MHz realtime tick
      }
    }
  }
  const double dots = (double)waves * iters * 256.0;
  printf("%-22s %8s %8s %13s %10s\n", "kernel", "ms", "TF/s", "cyc/dot/wave", "shaderMHz");
  for (int k = 0; k < nk; ++k) {
    // with W waves resident per SIMD at one dot per cycle, a wave needs W cycles per dot: 4.0 here
    printf("%-22s %8.2f %8.2f %13.3f %10.0f\n", kernels[k].name, best[k], dots * 32 * 2 * 2 / (best[k] * 1e-3) / 1e12,
           cyc[k] / ((double)iters * 256.0), mhz[k]);
  }
  return 0;
}
""")


if __name__ == "__main__":
    main()
